<?php
/**
 * ไฟล์: connectdb.php
 * เชื่อมต่อฐานข้อมูล 4115_db
 */

// --------------------------------
// 1. กำหนดค่าการเชื่อมต่อ (Configuration)
// --------------------------------
$db_host = "localhost";   // ชื่อโฮสต์
$db_user = "root";       // ชื่อผู้ใช้
$db_pass = "";         // รหัสผ่าน (ถ้าไม่มีให้ปล่อยว่าง "")
$db_name = "4115_db";    // *** ชื่อฐานข้อมูลตามที่คุณใช้ใน phpMyAdmin ***
$db_charset = "utf8mb4"; // Character Set ที่แนะนำสำหรับภาษาไทย

// --------------------------------
// 2. สร้างการเชื่อมต่อ (Establish Connection)
// --------------------------------

// ตัวแปร $conn นี้จะถูกนำไปใช้ในไฟล์อื่น ๆ (เช่น b.php หรือ f.php)
$conn = mysqli_connect($db_host, $db_user, $db_pass, $db_name);

// --------------------------------
// 3. ตรวจสอบและตั้งค่า (Check & Set)
// --------------------------------

// ตรวจสอบว่าเชื่อมต่อสำเร็จหรือไม่
if (!$conn) {
    // ถ้าเชื่อมต่อไม่สำเร็จ ให้หยุดการทำงานและแสดงข้อความผิดพลาด
    die("Connection failed: " . mysqli_connect_error());
}

// กำหนด Character Set ให้รองรับภาษาไทย
mysqli_set_charset($conn, $db_charset);

// ถ้าสำเร็จ จะมีเพียงตัวแปร $conn ที่พร้อมใช้งานในไฟล์อื่น
?>